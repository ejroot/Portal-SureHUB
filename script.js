const containerSem =
    document.getElementById("cards-sem-rollover");

const containerCom =
    document.getElementById("cards-com-rollover");

const counterSem =
    document.getElementById("counter-sem");

const counterCom =
    document.getElementById("counter-com");


/* ========================================
   CRIAR CARD
======================================== */

function criarCard(casa) {

    const semRollover =
        casa.categoria === "sem-rollover";


    const status =
        semRollover
            ? "Sem rollover"
            : "Com rollover";


    const statusClass =
        semRollover
            ? "status-green"
            : "status-orange";


    const card =
        document.createElement("article");


    card.classList.add("card");


    card.innerHTML = `

        <!-- TOPO DO CARD -->

        <div class="card-top">

            <!-- LOGO DA CASA -->

            <div class="bookmaker-logo">

                <img
                    src="${casa.logo}"
                    alt="Logo da ${casa.nome}"
                    loading="lazy"
                >

            </div>


            <!-- STATUS -->

            <span class="status ${statusClass}">
                ${status}
            </span>

        </div>


        <!-- NOME -->

        <h3>
            ${casa.nome}
        </h3>


        <!-- DESCRIÇÃO -->

        <p class="card-description">
            ${casa.descricao}
        </p>


        <!-- INFORMAÇÕES -->

        <div class="card-info">


            <div class="info-item">

                <span class="info-label">
                    Rollover
                </span>

                <span class="info-value">
                    ${casa.rollover}
                </span>

            </div>


            <div class="info-item">

                <span class="info-label">
                    Bônus
                </span>

                <span class="info-value">
                    ${casa.bonus}
                </span>

            </div>


        </div>


        <!-- BOTÃO -->

        <a
            href="${casa.url}"
            target="_blank"
            rel="noopener noreferrer"
            class="card-button"
        >
            Acessar casa
        </a>

    `;


    return card;
}


/* ========================================
   RENDERIZAR CASAS
======================================== */

function renderizarCasas() {

    containerSem.innerHTML = "";
    containerCom.innerHTML = "";


    /* CASAS SEM ROLLOVER */

    const casasSem =
        casas.filter(
            casa =>
                casa.categoria === "sem-rollover"
        );


    /* CASAS COM ROLLOVER */

    const casasCom =
        casas.filter(
            casa =>
                casa.categoria === "com-rollover"
        );


    /* RENDERIZA SEM ROLLOVER */

    casasSem.forEach(casa => {

        containerSem.appendChild(
            criarCard(casa)
        );

    });


    /* RENDERIZA COM ROLLOVER */

    casasCom.forEach(casa => {

        containerCom.appendChild(
            criarCard(casa)
        );

    });


    /* ATUALIZA CONTADORES */

    counterSem.textContent =
        `${casasSem.length} casas`;


    counterCom.textContent =
        `${casasCom.length} casas`;

}


/* ========================================
   INICIAR PORTAL
======================================== */

renderizarCasas();